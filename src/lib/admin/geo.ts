/** Département d'un code postal français (Corse : 2A / 2B). */
export function deptOf(zip: string | null | undefined): string | null {
  const z = (zip || '').replace(/\s/g, '');
  if (!/^\d{5}$/.test(z)) return null;
  if (z.startsWith('20')) return Number(z.slice(0, 3)) < 202 ? '2A' : '2B';
  const d = z.slice(0, 2);
  return DEPT[d] ? d : null;
}

export function lonLatOfZip(zip: string | null | undefined): [number, number] | null {
  const d = deptOf(zip);
  return d ? DEPT[d] : null;
}

