const NAMES = new Intl.DisplayNames(['fr'], { type: 'region' });

export function countryPoint(code: string | null | undefined): { code: string; name: string; lonlat: [number, number] | null } | null {
  const c = (code || '').toUpperCase();
  if (!/^[A-Z]{2}$/.test(c)) return null;
  let name = c;
  try { name = NAMES.of(c) || c; } catch { /* code inconnu */ }
  return { code: c, name, lonlat: COUNTRY[c] ?? null };
}
